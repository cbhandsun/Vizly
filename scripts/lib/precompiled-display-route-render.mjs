const groupPrecompiledRouteEntriesBySignature = entries => {
  const buckets = new Map();
  entries.forEach((entry, index) => {
    const bucket = buckets.get(entry.inputSignature) ?? [];
    bucket.push(index);
    buckets.set(entry.inputSignature, bucket);
  });
  return [...buckets.entries()];
};

export const renderPrecompiledRouteLoaders = entries => {
  const signatureBuckets = groupPrecompiledRouteEntriesBySignature(entries);
  const initialEntries = entries
    .map((entry, index) => ({ entry, index }))
    .filter(({ entry }) => entry.variantId === 'initial');
  return `import { loadBaseReactFlowPrecompiledRouteAsset } from '../baseReactFlowPrecompiledRouteAsset';

export type GeneratedBaseReactFlowPrecompiledRouteDescriptor = {
  presetId?: string;
  variantId: string;
  sourceHash: string;
  geometryDigest: string;
  load: () => Promise<unknown>;
};

${entries.map((entry, index) => `const generatedPrecompiledRouteAsset${index} = new URL(
  './precompiledRoutes/${entry.artifactFile}',
  import.meta.url,
);

const generatedPrecompiledRouteDescriptor${index}: GeneratedBaseReactFlowPrecompiledRouteDescriptor = {
  presetId: ${JSON.stringify(entry.presetId)},
  variantId: ${JSON.stringify(entry.variantId)},
  sourceHash: ${JSON.stringify(entry.sourceHash)},
  geometryDigest: ${JSON.stringify(entry.inputGeometryDigest)},
  load: () => loadBaseReactFlowPrecompiledRouteAsset(generatedPrecompiledRouteAsset${index}),
};`).join('\n\n')}

/** Generated by scripts/generate-precompiled-display-routes.mjs. */
export const GENERATED_BASE_REACT_FLOW_PRECOMPILED_ROUTE_LOADERS: Record<
  string,
  readonly GeneratedBaseReactFlowPrecompiledRouteDescriptor[]
> = {
${signatureBuckets.map(([inputSignature, indexes]) => (
    `  ${JSON.stringify(inputSignature)}: [${indexes
      .map(index => `generatedPrecompiledRouteDescriptor${index}`)
      .join(', ')}],`
  )).join('\n')}
};

/**
 * Preset ids only start an early chunk download. Runtime acceptance still uses
 * the complete signature, geometry digest, source hash, version, and output signature.
 */
export const GENERATED_BASE_REACT_FLOW_PRECOMPILED_ROUTE_PREFETCH_LOADERS: Record<
  string,
  GeneratedBaseReactFlowPrecompiledRouteDescriptor
> = {
${initialEntries.map(({ entry, index }) => (
    `  ${JSON.stringify(entry.presetId)}: generatedPrecompiledRouteDescriptor${index},`
  )).join('\n')}
};
`;
};

